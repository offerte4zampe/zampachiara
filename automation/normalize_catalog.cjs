const fs=require('node:fs'),zlib=require('node:zlib'),path=require('node:path');
const metadata=require('../site/assets/catalog-metadata.js');
const file=path.join(__dirname,'../site/data/catalog.json.gz');
const catalog=JSON.parse(zlib.gunzipSync(fs.readFileSync(file)));
const aliases=JSON.parse(fs.readFileSync(path.join(__dirname,'brand_aliases.json'),'utf8'));
const key=s=>String(s||'').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
const brands=new Map(Object.entries(aliases).flatMap(([k,v])=>[[key(k),v],[key(v),v]]));
const fishing=new Set(['shimano','rapala','gamakatsu','mustad','stonfo']);
const excluded=catalog.offers.filter(o=>fishing.has(key(o.brand)));
catalog.scope_exclusions={reason:'Fishing tackle outside pet catalog',brands:[...new Set(excluded.map(o=>o.brand))].sort(),offers:excluded.length};
catalog.offers=catalog.offers.filter(o=>!fishing.has(key(o.brand))).map(o=>metadata.normalize({...o,brand:brands.get(key(o.brand))||o.brand}));
fs.writeFileSync(file,zlib.gzipSync(JSON.stringify(catalog),{mtime:0}));
console.log(JSON.stringify({offers:catalog.offers.length,brands:new Set(catalog.offers.map(o=>o.brand)).size}));
